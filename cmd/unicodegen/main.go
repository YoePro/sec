/**
 * unicodeLetterRanges returns every Unicode letter code point range.
 *
 * Description:
 * Combines the five Unicode General_Category letter classes into
 * sorted, non-overlapping ranges.
 *
 * Parameters:
 * - db: The validated Unicode Character Database.
 *
 * Returns:
 * Inclusive code point ranges covering all Unicode letters.
 *
 * Allocation:
 * Allocates the resulting ranges during code generation.
 */
func unicodeLetterRanges(db *ucdDatabase) []codePointRange {
	return unicodeCategoryRanges(db, "Lu", "Ll", "Lt", "Lm", "Lo")
}

/**
 * renderCoreLetterTables generates Unicode letter classification for Sec core.
 *
 * Description:
 * Emits the Unicode 18.0 letter ranges and an internal lookup function.
 * The generated data is shared by the rune API and the standard library.
 *
 * Parameters:
 * - db: The validated Unicode Character Database.
 *
 * Returns:
 * Generated Sec source code for the core module.
 *
 * Allocation:
 * Allocates the generated source buffer during code generation.
 */
func renderCoreLetterTables(db *ucdDatabase) []byte {
	ranges := unicodeLetterRanges(db)
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go run ./cmd/unicodegen. DO NOT EDIT.")
	fmt.Fprintf(&out, "// Source: Unicode Character Database %s, General_Category L (Lu, Ll, Lt, Lm, Lo).\n\n", db.version)
	fmt.Fprintln(&out, "module core")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "type _UnicodeLetterRange struct {")
	fmt.Fprintln(&out, "    start: rune,")
	fmt.Fprintln(&out, "    end:   rune,")
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out)
	fmt.Fprintf(&out, "let _unicodeLetterRanges: _UnicodeLetterRange[%d] := [\n", len(ranges))
	for _, value := range ranges {
		fmt.Fprintf(&out, "    _UnicodeLetterRange{ start: 0x%06Xr, end: 0x%06Xr },\n", value.start, value.end)
	}
	fmt.Fprintln(&out, "]")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "/** Reports whether ch is a Unicode letter. */")
	fmt.Fprintln(&out, "fn _UnicodeIsLetter(ch: rune) bool {")
	fmt.Fprintln(&out, "    if ch < 0r || ch > 0x10FFFFr {")
	fmt.Fprintln(&out, "        return false")
	fmt.Fprintln(&out, "    }")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "    if ch <= 0x007Fr {")
	fmt.Fprintln(&out, "        return ch in 0x0041r..0x005Ar || ch in 0x0061r..0x007Ar")
	fmt.Fprintln(&out, "    }")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "    let mut low := 0")
	fmt.Fprintf(&out, "    let mut high := %d\n", len(ranges)-1)
	fmt.Fprintln(&out, "    while low <= high {")
	fmt.Fprintln(&out, "        let middle := low + (high - low) / 2")
	fmt.Fprintln(&out, "        let current := _unicodeLetterRanges[middle]")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "        if ch < current.start {")
	fmt.Fprintln(&out, "            high = middle - 1")
	fmt.Fprintln(&out, "            continue")
	fmt.Fprintln(&out, "        }")
	fmt.Fprintln(&out, "        if ch > current.end {")
	fmt.Fprintln(&out, "            low = middle + 1")
	fmt.Fprintln(&out, "            continue")
	fmt.Fprintln(&out, "        }")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "        return true")
	fmt.Fprintln(&out, "    }")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "    return false")
	fmt.Fprintln(&out, "}")
	return out.Bytes()
}

func tableContains(ranges []codePointRange, value rune) bool {
	if value < 0 || value > maxCodePoint {
		return false
	}
	low := 0
	high := len(ranges) - 1
	for low <= high {
		middle := low + (high-low)/2
		current := ranges[middle]
		if value < current.start {
			high = middle - 1
			continue
		}
		if value > current.end {
			low = middle + 1
			continue
		}
		return true
	}
	return false
}

/**
 * unicodeDecimalZeros returns the starting code point of each Unicode
 * decimal digit set.
 *
 * Description:
 * Uses the Unicode General_Category Nd from the loaded UCD database.
 * Each decimal digit set contains ten consecutive code points, 0 through 9.
 * Adjacent sets are split into individual ten-digit groups.
 *
 * Parameters:
 * - db: The validated Unicode Character Database.
 *
 * Returns:
 * The zero code point for each decimal digit set, in ascending order.
 *
 * Errors:
 * Returns an error if a contiguous Nd range cannot be divided
 * into complete ten-digit groups.
 *
 * Allocation:
 * Allocates the resulting slice during code generation only.
 */
func unicodeDecimalZeros(db *ucdDatabase) ([]rune, error) {
	ranges := rangesWhere(func(ch rune) bool {
		return db.category(ch) == "Nd"
	})

	var zeros []rune

	for _, group := range ranges {
		count := group.end - group.start + 1

		if count%10 != 0 {
			return nil, fmt.Errorf(
				"invalid Unicode decimal digit range U+%04X..U+%04X",
				group.start, group.end,
			)
		}

		for zero := group.start; zero <= group.end; zero += 10 {
			zeros = append(zeros, zero)
		}
	}

	return zeros, nil
}

/**
 * renderCoreDecimalDigits generates the Unicode decimal digit table
 * used by Sec core.
 *
 * Description:
 * Writes the zero code point for each Unicode decimal digit set.
 * The generated table is independent of the standard library.
 *
 * Parameters:
 * - db: The validated Unicode Character Database.
 *
 * Returns:
 * Generated Sec source code.
 *
 * Errors:
 * Returns an error if the Unicode decimal digit data is inconsistent.
 *
 * Allocation:
 * Allocates memory during code generation only.
 */
func renderCoreDecimalDigits(db *ucdDatabase) ([]byte, error) {
	zeros, err := unicodeDecimalZeros(db)
	if err != nil {
		return nil, err
	}

	var out bytes.Buffer

	fmt.Fprintln(&out, "// Code generated by unicodegen. DO NOT EDIT.")
	fmt.Fprintln(&out, "module core")
	fmt.Fprintln(&out)
	fmt.Fprintf(&out, "let _decimalZeros: rune[%d] := [\n", len(zeros))

	for _, zero := range zeros {
		fmt.Fprintf(&out, "    0x%06Xr,\n", zero)
	}

	fmt.Fprintln(&out, "]")

	return out.Bytes(), nil
}

/**
 * unicodeCategoryRanges returns the code point ranges belonging to
 * one or more Unicode General_Category values.
 *
 * Description:
 * Reads the categories from the validated Unicode Character Database.
 * Consecutive matching code points are merged into inclusive ranges.
 * Multiple categories may be combined into a single result.
 *
 * Parameters:
 * - db: The validated Unicode Character Database.
 * - categories: Unicode General_Category identifiers, such as
 *   Lu, Ll, Lt, Nd, Mn, Po, or Sc.
 *
 * Returns:
 * Sorted, non-overlapping ranges covering the selected categories.
 * An empty category list produces an empty result.
 *
 * Allocation:
 * Allocates the resulting ranges during code generation.
 */
func unicodeCategoryRanges(db *ucdDatabase, categories ...string) []codePointRange {
	return rangesWhere(func(ch rune) bool {
		category := db.category(ch)

		for _, wanted := range categories {
			if category == wanted {
				return true
			}
		}

		return false
	})
}

/**
 * renderLetterTables generates the public Unicode letter API.
 *
 * Description:
 * Delegates Unicode letter classification to Sec core so that
 * the Unicode letter table is stored only once.
 *
 * Parameters:
 * - db: The validated Unicode Character Database.
 *
 * Returns:
 * Generated Sec source code for the unicode module.
 *
 * Allocation:
 * Allocates the generated source buffer during code generation.
 */
func renderLetterTables(db *ucdDatabase) []byte {
	return fmt.Appendf(nil, `// Code generated by unicodegen. DO NOT EDIT.
// Unicode Character Database %s.

module unicode

/**
 * Reports whether a Unicode scalar is a letter.
 *
 * Parameters:
 * - ch: The Unicode scalar to classify.
 *
 * Returns:
 * True for Unicode letter categories Lu, Ll, Lt, Lm and Lo.
 *
 * Allocation:
 * Does not allocate.
 */
fn IsLetter(ch: rune) bool {
    return ch.IsLetter
}
`, db.version)
}
