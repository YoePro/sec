package main

import (
	"fmt"
	"sort"
	"strings"
)

// caseRun is a maximal run of code points start, start+stride, ... end whose
// simple case mapping adds the same delta. Stride is 1 or 2, which covers the
// alternating upper/lower layout of Latin Extended and similar blocks.
type caseRun struct {
	start, end rune
	stride     int
	delta      int
}

// caseRuns compresses one explicit simple mapping into sorted runs.
// Rules: rules/library/core-library.md — §11.3 (UAX #44 simple case mapping).
func caseRuns(mapping map[rune]rune) []caseRun {
	points := make([]rune, 0, len(mapping))
	for point, mapped := range mapping {
		if mapped != point {
			points = append(points, point)
		}
	}
	sort.Slice(points, func(i, j int) bool { return points[i] < points[j] })
	var runs []caseRun
	for _, point := range points {
		delta := int(mapping[point]) - int(point)
		if n := len(runs); n > 0 {
			last := &runs[n-1]
			gap := int(point - last.end)
			if last.delta == delta && (last.start == last.end && (gap == 1 || gap == 2) || gap == last.stride) {
				if last.start == last.end {
					last.stride = gap
				}
				last.end = point
				continue
			}
		}
		runs = append(runs, caseRun{start: point, end: point, stride: 1, delta: delta})
	}
	return runs
}

// mapThroughRuns applies runs to value exactly as the generated Sec lookup does.
func mapThroughRuns(runs []caseRun, value rune) rune {
	index := sort.Search(len(runs), func(i int) bool { return runs[i].end >= value })
	if index < len(runs) && runs[index].start <= value && int(value-runs[index].start)%runs[index].stride == 0 {
		return value + rune(runs[index].delta)
	}
	return value
}

// renderCoreCaseMappings emits the simple uppercase, lowercase and titlecase
// tables and their lookups. Titlecase falls back to uppercase as UAX #44
// specifies. Rules: rules/library/core-library.md — §11.3.
func renderCoreCaseMappings(db *ucdDatabase) ([]byte, error) {
	title := map[rune]rune{}
	for point, mapped := range db.simpleUpper {
		title[point] = mapped
	}
	for point, mapped := range db.simpleTitle {
		title[point] = mapped
	}
	tables := []struct {
		name    string
		mapping map[rune]rune
		check   func(rune) rune
	}{
		{"Upper", db.simpleUpper, db.simpleUppercase},
		{"Lower", db.simpleLower, db.simpleLowercase},
		{"Title", title, db.simpleTitlecase},
	}
	var out strings.Builder
	fmt.Fprintf(&out, `// Code generated by go run ./cmd/unicodegen. DO NOT EDIT.
// Unicode Character Database %s; simple case mappings (UnicodeData.txt fields 12-14).

module core
`, db.version)
	for _, table := range tables {
		runs := caseRuns(table.mapping)
		for value := rune(0); value <= maxCodePoint; value++ {
			if mapThroughRuns(runs, value) != table.check(value) {
				return nil, fmt.Errorf("simple %s mapping of U+%04X does not survive compression", strings.ToLower(table.name), value)
			}
		}
		lower := strings.ToLower(table.name)
		fmt.Fprintf(&out, "\n// Simple %s runs: inclusive scalar pairs, then each run's stride and delta.\n", lower)
		fmt.Fprintf(&out, "let _unicodeCase%sRanges: rune[%d] := [\n", table.name, 2*len(runs))
		for _, run := range runs {
			fmt.Fprintf(&out, "    0x%06Xr, 0x%06Xr,\n", run.start, run.end)
		}
		out.WriteString("]\n")
		fmt.Fprintf(&out, "let _unicodeCase%sStrides: uint[%d] := [\n", table.name, len(runs))
		for _, run := range runs {
			fmt.Fprintf(&out, "    %d,\n", run.stride)
		}
		out.WriteString("]\n")
		fmt.Fprintf(&out, "let _unicodeCase%sDeltas: int[%d] := [\n", table.name, len(runs))
		for _, run := range runs {
			fmt.Fprintf(&out, "    %d,\n", run.delta)
		}
		out.WriteString("]\n")
		fmt.Fprintf(&out, `
/** Unicode simple %[1]s mapping of a scalar; unmapped scalars map to themselves. Rules: rules/library/core-library.md §11.3. */
fn _UnicodeSimple%[2]s(ch: rune) rune {
    let mut low: uint := 0
    let mut high: uint := _unicodeCase%[2]sStrides.Len
    while low < high {
        let middle := low + (high - low) / 2
        if ch > _unicodeCase%[2]sRanges[2 * middle + 1] {
            low = middle + 1
        } else if ch < _unicodeCase%[2]sRanges[2 * middle] {
            high = middle
        } else {
            let offset := uint(ch) - uint(_unicodeCase%[2]sRanges[2 * middle])
            if offset %% _unicodeCase%[2]sStrides[middle] != 0 {
                return ch
            }
            return try rune(int(ch) + _unicodeCase%[2]sDeltas[middle]) {
                Err(_) => ch
            }
        }
    }
    return ch
}
`, lower+"case", table.name)
	}
	return []byte(out.String()), nil
}

// fullMapping is one scalar whose full mapping is not its simple mapping.
type fullMapping struct {
	point rune
	runes []rune
}

// fullMappings lists the unconditional SpecialCasing.txt entries of one kind
// (0 lower, 1 title, 2 upper) that differ from the simple mapping.
func (db *ucdDatabase) fullMappings(kind int, simple func(rune) rune) []fullMapping {
	var result []fullMapping
	for _, entry := range db.specialCasing {
		if len(entry.conditions) != 0 {
			continue
		}
		runes := [][]rune{entry.lower, entry.title, entry.upper}[kind]
		if len(runes) == 1 && runes[0] == simple(entry.codePoint) {
			continue
		}
		result = append(result, fullMapping{point: entry.codePoint, runes: runes})
	}
	sort.Slice(result, func(i, j int) bool { return result[i].point < result[j].point })
	return result
}

// foldMappings lists every C+F full case folding that is not the identity.
func (db *ucdDatabase) foldMappings() []fullMapping {
	var result []fullMapping
	for point, runes := range db.fullFolding {
		if len(runes) == 1 && runes[0] == point {
			continue
		}
		result = append(result, fullMapping{point: point, runes: runes})
	}
	sort.Slice(result, func(i, j int) bool { return result[i].point < result[j].point })
	return result
}

// renderCoreFullCaseMappings emits the public rune full case mapping API over
// generated SpecialCasing (unconditional) and CaseFolding (C+F) data. Context-
// and language-dependent mappings (Final_Sigma, tr/az/lt) are not included;
// callers that see context apply them. Rules: rules/library/core-library.md
// §11.3; stdlib/str/stdlib_str.md §§9.3–9.6.
func renderCoreFullCaseMappings(db *ucdDatabase) ([]byte, error) {
	var out strings.Builder
	fmt.Fprintf(&out, `// Code generated by go run ./cmd/unicodegen. DO NOT EDIT.
// Unicode Character Database %s; full case mappings (SpecialCasing.txt
// unconditional entries) and full case folding (CaseFolding.txt C+F).

module core

/**
 * The one to three runes a full case mapping or folding of one rune produces.
 *
 * Description:
 * Count is 1, 2 or 3; runes beyond Count are U+0000 and carry no meaning.
 */
type RuneCaseMapping struct {
    Count: uint,
    First: rune,
    Second: rune,
    Third: rune,
}
`, db.version)
	tables := []struct {
		name     string
		mappings []fullMapping
	}{
		{"Lower", db.fullMappings(0, db.simpleLowercase)},
		{"Title", db.fullMappings(1, db.simpleTitlecase)},
		{"Upper", db.fullMappings(2, db.simpleUppercase)},
		{"Fold", db.foldMappings()},
	}
	for _, table := range tables {
		fmt.Fprintf(&out, "\nlet _unicodeFull%sPoints: rune[%d] := [\n", table.name, len(table.mappings))
		for _, mapping := range table.mappings {
			fmt.Fprintf(&out, "    0x%06Xr,\n", mapping.point)
		}
		out.WriteString("]\n")
		fmt.Fprintf(&out, "let _unicodeFull%sRunes: rune[%d] := [\n", table.name, 3*len(table.mappings))
		for _, mapping := range table.mappings {
			if len(mapping.runes) == 0 || len(mapping.runes) > 3 {
				return nil, fmt.Errorf("full %s mapping of U+%04X has %d runes", table.name, mapping.point, len(mapping.runes))
			}
			parts := []string{}
			for index := 0; index < 3; index++ {
				value := rune(0)
				if index < len(mapping.runes) {
					value = mapping.runes[index]
				}
				parts = append(parts, fmt.Sprintf("0x%06Xr", value))
			}
			fmt.Fprintf(&out, "    %s,\n", strings.Join(parts, ", "))
		}
		out.WriteString("]\n")
		fmt.Fprintf(&out, "let _unicodeFull%sCounts: uint[%d] := [\n", table.name, len(table.mappings))
		for _, mapping := range table.mappings {
			fmt.Fprintf(&out, "    %d,\n", len(mapping.runes))
		}
		out.WriteString("]\n")
		fmt.Fprintf(&out, `
// The generated full %[1]s entry of ch, or a one-rune mapping to fallback.
fn _UnicodeFull%[1]s(ch: rune, fallback: rune) RuneCaseMapping {
    let mut low: uint := 0
    let mut high: uint := _unicodeFull%[1]sPoints.Len
    while low < high {
        let middle := low + (high - low) / 2
        let point := _unicodeFull%[1]sPoints[middle]
        if ch > point {
            low = middle + 1
        } else if ch < point {
            high = middle
        } else {
            return RuneCaseMapping {
                Count: _unicodeFull%[1]sCounts[middle],
                First: _unicodeFull%[1]sRunes[3 * middle],
                Second: _unicodeFull%[1]sRunes[3 * middle + 1],
                Third: _unicodeFull%[1]sRunes[3 * middle + 2],
            }
        }
    }
    return RuneCaseMapping { Count: 1, First: fallback, Second: 0r, Third: 0r }
}
`, table.name)
	}
	out.WriteString(`
impl extends rune {
    /**
     * Returns the full lowercase mapping of this rune.
     *
     * Description:
     * Applies the unconditional SpecialCasing.txt entry when one exists (for
     * example U+0130 maps to "i" plus U+0307), otherwise the simple lowercase
     * mapping. Context-dependent mappings such as Greek final sigma and
     * language-specific mappings are not applied; whole-string conversion in
     * stdlib/str applies the context.
     *
     * Allocation:
     * Does not allocate.
     */
    fn FullLowercase() RuneCaseMapping {
        return _UnicodeFullLower(self, self.ToLower())
    }

    /**
     * Returns the full uppercase mapping of this rune, for example U+00DF
     * (sharp s) maps to "SS". Falls back to the simple uppercase mapping.
     *
     * Allocation:
     * Does not allocate.
     */
    fn FullUppercase() RuneCaseMapping {
        return _UnicodeFullUpper(self, self.ToUpper())
    }

    /**
     * Returns the full titlecase mapping of this rune, for example U+00DF
     * maps to "Ss". Falls back to the simple titlecase mapping.
     *
     * Allocation:
     * Does not allocate.
     */
    fn FullTitlecase() RuneCaseMapping {
        return _UnicodeFullTitle(self, self.ToTitle())
    }

    /**
     * Returns the full, locale-independent case folding of this rune
     * (CaseFolding.txt statuses C and F), for example U+00DF folds to "ss".
     * A rune without a folding maps to itself. Turkic (T) foldings are not
     * applied.
     *
     * Allocation:
     * Does not allocate.
     */
    fn FullCaseFold() RuneCaseMapping {
        return _UnicodeFullFold(self, self)
    }
}
`)
	return []byte(out.String()), nil
}
